/**
 * The demo's Next CLI runner.
 *
 * All secrets live once in the repository-root `.env.local`, but `next dev`
 * / `next start` scan only the app directory for env files, and their server
 * workers do not reliably inherit what a config file or the parent process
 * loads. So this runner:
 *
 *   1. loads the root env files (root `.env.local`, `.env`, ...),
 *   2. writes the resulting key/value set into `apps/web/.env.local` - the
 *      one location Next applies natively to every worker,
 *   3. hands the process over to the Next CLI with the arguments untouched.
 *
 * Only values that already exist in the root env files are written; nothing
 * is invented, and the file is regenerated on every boot. `apps/web/.env.local`
 * is covered by the `.env.*` gitignore rule - never commit it. Restart
 * `npm run dev` after editing the root `.env.local` (a fresh token included).
 */
import path from 'node:path';
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import nextEnv from '@next/env';

const appDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(appDir, '../..');

const loaded = nextEnv.loadEnvConfig(rootDir);

const combinedEnv = loaded?.combinedEnv ?? {};
const generated = [
  '# Generated by next-runner.mjs from the repository-root .env.local - do not edit.',
  '# Delete this file without worry; it is rebuilt on every `npm run dev` / `npm run start`.',
  ...Object.keys(combinedEnv)
    .sort()
    .map((key) => `${key}=${combinedEnv[key] ?? ''}`),
  '',
].join('\n');
writeFileSync(path.join(appDir, '.env.local'), generated, 'utf8');

// next's bin sets itself up from process.argv - swap only the bin entry so
// `dev -p 3000` style arguments keep arriving in the order Next expects.
const require = createRequire(import.meta.url);
let bin = path.resolve(appDir, '../node_modules/next/dist/bin/next');
if (!existsSync(bin)) {
  bin = require.resolve('next/dist/bin/next');
}
process.argv[1] = bin;

await import(pathToFileURL(bin).href);
